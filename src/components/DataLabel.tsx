// Labels that tell the reader where a piece of information came from.
// These appear throughout the report so observed data is never confused with AI output.

export type DataKind = "observed" | "computed" | "ai" | "hypothesis";

const STYLES: Record<DataKind, { text: string; className: string; title: string }> = {
  observed: {
    text: "Observed data",
    className: "border-sky-500/40 bg-sky-500/10 text-sky-300",
    title: "Returned by a marketplace API or quoted verbatim from a cited web source.",
  },
  computed: {
    text: "Computed",
    className: "border-zinc-500/40 bg-zinc-500/10 text-zinc-300",
    title: "Calculated by Drop Lab from the observed data. No AI involved.",
  },
  ai: {
    text: "AI interpretation",
    className: "border-violet-500/40 bg-violet-500/10 text-violet-300",
    title: "Generated by Claude from the observed data. May be wrong - check the cited evidence.",
  },
  hypothesis: {
    text: "Hypothesis to test",
    className: "border-amber-500/40 bg-amber-500/10 text-amber-300",
    title: "Not a prediction. Needs validation with real customers.",
  },
};

export function DataLabel({ kind }: { kind: DataKind }) {
  const style = STYLES[kind];
  return (
    <span
      title={style.title}
      className={`inline-flex shrink-0 items-center rounded-full border px-2 py-0.5 text-[11px] font-medium uppercase tracking-wide ${style.className}`}
    >
      {style.text}
    </span>
  );
}

/** Shown wherever a value could not be verified. */
export function Unavailable({ reason }: { reason?: string }) {
  return (
    <span className="text-zinc-500 italic" title={reason ?? "This data point could not be verified."}>
      Unavailable
    </span>
  );
}

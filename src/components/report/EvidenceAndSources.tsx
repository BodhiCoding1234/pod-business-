import { formatDateTime, PROVIDER_LABELS } from "@/lib/format";
import type { ResearchReport } from "@/lib/research/report";
import type { ObservationKind } from "@/lib/research/types";
import { Card, Section } from "./Section";

const KIND_LABELS: Record<ObservationKind, string> = {
  cited_excerpt: "Quoted excerpt",
  search_result: "Search result",
  result_count: "Result count",
};

export function EvidenceList({ report }: { report: ResearchReport }) {
  const { observations } = report.evidence;
  return (
    <Section
      id="evidence"
      title="Evidence"
      description="Other observations collected from the data sources. Listings (L…) are in the Competition table above."
    >
      <Card title={`Observations (${observations.length})`} kind="observed">
        {observations.length === 0 ? (
          <p className="text-zinc-500">No observations were collected.</p>
        ) : (
          <ul className="-mx-5 divide-y divide-zinc-800/60">
            {observations.map((o) => (
              <li key={o.id} id={o.id} className="flex gap-3 px-5 py-2.5">
                <span className="w-10 shrink-0 font-mono text-xs text-zinc-500">{o.id}</span>
                <div className="min-w-0">
                  <p className="text-xs text-zinc-500">
                    {PROVIDER_LABELS[o.provider]} · {KIND_LABELS[o.kind]}
                  </p>
                  <p className={o.kind === "cited_excerpt" ? "text-zinc-200 italic" : "text-zinc-200"}>
                    {o.kind === "cited_excerpt" ? `“${o.text}”` : o.text}
                  </p>
                  {o.sourceUrl && (
                    <a
                      href={o.sourceUrl}
                      target="_blank"
                      rel="noreferrer"
                      className="block truncate text-xs text-sky-400 hover:text-sky-300"
                    >
                      {o.sourceTitle ?? o.sourceUrl}
                    </a>
                  )}
                </div>
              </li>
            ))}
          </ul>
        )}
      </Card>
    </Section>
  );
}

export function DataSources({ report }: { report: ResearchReport }) {
  const analysis = report.analysis;
  return (
    <Section id="sources" title="Data sources & limitations">
      <div className="grid gap-4 md:grid-cols-2">
        {report.providers.map((p) => (
          <Card key={p.provider} title={p.label}>
            {p.status === "error" ? (
              <p className="text-rose-300">Failed: {p.errorMessage}</p>
            ) : (
              <>
                <p className="text-xs text-zinc-500">
                  Query “{p.output?.query}” · fetched {formatDateTime(p.fetchedAt)}
                </p>
                <ul className="mt-2 list-disc space-y-1 pl-5 text-zinc-400 marker:text-zinc-600">
                  {p.output?.notes.map((note, index) => <li key={index}>{note}</li>)}
                </ul>
              </>
            )}
          </Card>
        ))}
        {analysis && (
          <Card title="Claude analysis">
            {analysis.status === "complete" ? (
              <>
                <p className="text-zinc-400">Generated by {analysis.model}.</p>
                {analysis.removedReferences.length > 0 && (
                  <p className="mt-2 text-amber-300">
                    Removed {analysis.removedReferences.length} citation(s) to evidence that does not exist:{" "}
                    <span className="font-mono text-xs">{analysis.removedReferences.join(", ")}</span>
                  </p>
                )}
              </>
            ) : (
              <p className={analysis.status === "error" ? "text-rose-300" : "text-zinc-400"}>
                {analysis.status === "error" ? "Failed: " : "Skipped: "}
                {analysis.message}
              </p>
            )}
          </Card>
        )}
      </div>
    </Section>
  );
}
